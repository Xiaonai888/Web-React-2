/**
 * Shadow Realms — Farmer entity (Stage 1, Step 7).
 *
 * One independently updateable, selectable farmer. No requests, assets,
 * storage or game-page dependencies. The body's Canvas art is replaceable.
 *
 * Usage (after wiring the game page in a later step):
 *   import { Farmer } from './characters/Farmer.js'
 *   const spawn = engine.map.getSpawnPoint('blue')
 *   const farmer = new Farmer({ id: 'f1', ...spawn })
 *   // engine.onUpdate: farmer.update(dt, engine.map)
 *   // engine.onRender: farmer.draw(ctx, engine.camera)
 *   // selection.getUnits: () => [farmer]
 *   // selection.onCommand: ({type,point}) => {
 *   //   if (type === 'move') farmer.moveTo(point)
 *   // }
 *
 * moveTo() is direct movement; setPath() accepts waypoints from a future
 * pathfinder. All steps honor WorldMap.isWalkable(), so no walking through
 * river water, trees, rocks or outside map bounds.
 */

const TAU = Math.PI * 2
const clamp = (value, min, max) => Math.min(max, Math.max(min, value))
const validPoint = p => Number.isFinite(p?.x) && Number.isFinite(p?.y)
const distance = (a, b) => Math.hypot(a.x - b.x, a.y - b.y)
const fillOval = (ctx, x, y, rx, ry, color) => {
  ctx.fillStyle = color
  ctx.beginPath()
  ctx.ellipse(x, y, rx, ry, 0, 0, TAU)
  ctx.fill()
}
const line = (ctx, x1, y1, x2, y2, width, color) => {
  ctx.strokeStyle = color
  ctx.lineWidth = width
  ctx.lineCap = 'round'
  ctx.beginPath()
  ctx.moveTo(x1, y1)
  ctx.lineTo(x2, y2)
  ctx.stroke()
}

let nextFarmerId = 1

export class Farmer {
  constructor({
    id = null,
    name = 'Farmer',
    team = 'blue',
    x = 400,
    y = 1100,
    hp = 100,
    speed = 115,
    radius = 14,
    renderer = null,
  } = {}) {
    this.id = id ?? `farmer-${nextFarmerId++}`
    this.name = String(name)
    this.type = 'farmer'
    this.team = team
    this.x = Number.isFinite(x) ? x : 400
    this.y = Number.isFinite(y) ? y : 1100
    this.hp = clamp(Number.isFinite(hp) ? hp : 100, 0, 100)
    this.maxHp = 100
    this.speed = clamp(Number.isFinite(speed) ? speed : 115, 15, 500)
    this.radius = clamp(Number.isFinite(radius) ? radius : 14, 6, 35)
    this.selectable = true
    this.alive = this.hp > 0
    this.state = 'idle'                 // idle | walking | blocked | harvesting | dead
    this.facing = 'down'
    this.angle = Math.PI / 2
    this.motionTime = 0
    this.lifetime = 0
    this.carry = 0                      // Future rice inventory; no economy yet.
    this.path = []
    this.destination = null
    this.blockedSeconds = 0
    this.renderer = renderer           // Future Manga sprite painter callback.
    this.onArrive = null
    this.onBlocked = null
  }

  /** Set a direct point; if obstructed, stop safely (Pathfinding.js comes later). */
  moveTo(point) {
    if (!this.alive || !validPoint(point)) return false
    return this.setPath([point])
  }

  /** Accept points generated by the future, independent Pathfinding module. */
  setPath(points) {
    if (!this.alive || !Array.isArray(points)) return false
    if (!points.length) { this.stop(); return false }
    const validPoints = Array.from(points)
    if (!validPoints.every(validPoint)) return false
    const path = validPoints.map(p => ({ x: p.x, y: p.y }))
    this.path = path
    this.destination = path[path.length - 1]
    this.blockedSeconds = 0
    this.state = 'walking'
    return true
  }

  stop() {
    this.path = []
    this.destination = null
    this.blockedSeconds = 0
    if (this.alive) this.state = 'idle'
  }

  /** Only an animation state for now. Harvesting resources is a later module. */
  setHarvestAnimation(active) {
    if (!this.alive) return
    if (active) {
      this.path = []
      this.destination = null
      this.state = 'harvesting'
    } else if (this.state === 'harvesting') this.state = 'idle'
  }

  takeDamage(amount) {
    if (!this.alive || !Number.isFinite(amount) || amount <= 0) return this.hp
    this.hp = Math.max(0, this.hp - amount)
    if (this.hp === 0) {
      this.alive = false
      this.selectable = false
      this.state = 'dead'
      this.path = []
      this.destination = null
    }
    return this.hp
  }

  /** Low HP affects movement; shares the same rule with future unit types. */
  get condition() {
    const ratio = this.hp / this.maxHp
    return ratio >= 0.65 ? 1 : ratio >= 0.3 ? 0.75 : 0.55
  }

  update(dt, map) {
    if (!this.alive || !Number.isFinite(dt) || dt <= 0) return
    const delta = clamp(dt, 0, 0.05)
    this.lifetime += delta
    if (this.state !== 'walking' || !this.path.length) {
      if (this.state === 'harvesting') this.motionTime += delta * 6
      return
    }

    const waypoint = this.path[0]
    const dx = waypoint.x - this.x
    const dy = waypoint.y - this.y
    const remaining = Math.hypot(dx, dy)
    const step = this.speed * this.condition * delta
    if (remaining <= Math.max(2.5, step)) {
      if (this.#canOccupy(waypoint.x, waypoint.y, map)) {
        this.x = waypoint.x
        this.y = waypoint.y
        this.path.shift()
        this.blockedSeconds = 0
        if (!this.path.length) {
          this.destination = null
          this.state = 'idle'
          try { this.onArrive?.(this) }
          catch (error) { console.warn('Shadow Realms farmer arrival callback failed:', error) }
        }
        return
      }
    }
    if (remaining < 0.001) {
      // A new wall may occupy a previously accepted waypoint. Do not remain
      // permanently in 'walking' with an unreachable zero-distance target.
      this.blockedSeconds += delta
      if (this.blockedSeconds >= 0.45) this.#blocked()
      return
    }

    const nx = dx / remaining
    const ny = dy / remaining
    this.angle = Math.atan2(dy, dx)
    this.facing = Math.abs(nx) > Math.abs(ny) * 1.25
      ? nx > 0 ? 'right' : 'left'
      : ny > 0 ? 'down' : 'up'

    // Substeps prevent skipping through thin barriers at low frame rates.
    const total = Math.min(step, remaining)
    const segments = Math.max(1, Math.ceil(total / Math.max(3, this.radius * 0.44)))
    const sx = nx * total / segments
    const sy = ny * total / segments
    let moved = 0
    for (let i = 0; i < segments; i++) {
      const oldX = this.x
      const oldY = this.y
      if (this.#canOccupy(this.x + sx, this.y + sy, map)) {
        this.x += sx
        this.y += sy
      } else if (this.#canOccupy(this.x + sx, this.y, map)) {
        this.x += sx
      } else if (this.#canOccupy(this.x, this.y + sy, map)) {
        this.y += sy
      } else break
      moved += Math.hypot(this.x - oldX, this.y - oldY)
    }

    this.motionTime += moved * 0.14
    this.blockedSeconds = moved <= 0.05 ? this.blockedSeconds + delta : 0
    if (this.blockedSeconds >= 0.45) this.#blocked()
  }

  #blocked() {
    const failedPoint = this.destination ? { ...this.destination } : null
    this.path = []
    this.destination = null
    this.state = 'blocked'
    try { this.onBlocked?.(this, failedPoint) }
    catch (error) { console.warn('Shadow Realms farmer blocked callback failed:', error) }
  }

  #canOccupy(x, y, map) {
    return !map || typeof map.isWalkable !== 'function' ||
      map.isWalkable(x, y, this.radius)
  }

  /** Screen-space upright chibi on a tilted world; swap renderer for a sprite. */
  draw(ctx, camera) {
    if (!this.alive || !ctx || !camera) return
    const p = camera.worldToScreen(this.x, this.y)
    const scale = clamp(camera.zoom, 0.35, 2.4)
    const w = camera.viewportWidth
    const h = camera.viewportHeight
    if (p.x < -58 * scale || p.x > w + 58 * scale ||
        p.y < -82 * scale || p.y > h + 28 * scale) return

    ctx.save()
    ctx.translate(p.x, p.y)
    // Soft floor shadow stays tilted, while character silhouette stays upright.
    fillOval(ctx, 4 * scale, 3 * scale, 18 * scale, 6 * scale,
      'rgba(23,40,26,.24)')
    ctx.scale(scale, scale)

    if (typeof this.renderer === 'function') {
      this.renderer(ctx, this)
    } else {
      this.#drawChibi(ctx)
    }
    ctx.restore()
  }

  #drawChibi(ctx) {
    const isWalking = this.state === 'walking'
    const harvesting = this.state === 'harvesting'
    const swing = isWalking ? Math.sin(this.motionTime) * 5.5 : 0
    const bounce = isWalking ? Math.abs(Math.sin(this.motionTime)) * 1.5 :
      Math.sin(this.lifetime * 2.2) * 0.6
    const action = harvesting ? Math.sin(this.motionTime * 1.4) * 7 : 0
    const shirt = this.team === 'red' ? '#a93840' : '#356cb5'
    const shadowShirt = this.team === 'red' ? '#762b36' : '#244e87'
    const backView = this.facing === 'up'
    const side = this.facing === 'left' ? -1 : 1

    ctx.save()
    ctx.translate(0, -bounce)
    ctx.scale(side, 1)

    // Boots and moving legs (slightly staggered to create depth).
    line(ctx, -5, -12, -5 + swing * 0.5, -2 + Math.max(0, -swing) * 0.25, 6, '#44362f')
    line(ctx, 5, -12, 5 - swing * 0.5, -2 + Math.max(0, swing) * 0.25, 6, '#322d29')
    fillOval(ctx, -5 + swing * 0.5, 0, 5.5, 3, '#2a2f31')
    fillOval(ctx, 5 - swing * 0.5, 0, 5.5, 3, '#262b2b')

    // Rear arm and optional rice-carrying bag.
    line(ctx, -12, -28, -14 + swing * 0.5, -16, 6, shadowShirt)
    if (this.carry > 0) {
      fillOval(ctx, -13, -21, 8, 10, '#d8bf76')
      line(ctx, -19, -22, -8, -22, 2, '#9d7739')
    }

    // Shirt: curved sides, lighter front plane, belt and sash.
    ctx.fillStyle = shadowShirt
    ctx.beginPath()
    ctx.moveTo(-9, -36)
    ctx.lineTo(10, -36)
    ctx.lineTo(11, -13)
    ctx.quadraticCurveTo(0, -8, -11, -13)
    ctx.closePath()
    ctx.fill()
    ctx.fillStyle = shirt
    ctx.beginPath()
    ctx.moveTo(-8, -35)
    ctx.lineTo(5, -35)
    ctx.lineTo(6, -16)
    ctx.lineTo(-8, -16)
    ctx.closePath()
    ctx.fill()
    line(ctx, -8, -15, 9, -15, 3.2, '#b58b51')
    fillOval(ctx, 0, -15, 2.2, 2.2, '#e3bd74')

    // Front arm and a curved sickle. Animation is visual only for now.
    line(ctx, 11, -30, 15 + swing * 0.4, -18 - action * 0.3, 6, shirt)
    const gripY = -13 - action * 0.55
    line(ctx, 15 + swing * 0.4, -20 - action * 0.3, 16 + action, gripY,
      5, '#dbab77')
    line(ctx, 16 + action, gripY, 20 + action, gripY - 13, 3.3, '#765039')
    ctx.strokeStyle = '#dbe2da'
    ctx.lineWidth = 3
    ctx.lineCap = 'round'
    ctx.beginPath()
    ctx.arc(15 + action, gripY - 19, 8, -0.7, 1.95)
    ctx.stroke()

    // Large chibi head, nose, shaded cheeks, eyes and straw hat.
    fillOval(ctx, 0, -45, 15.5, 15, '#c78f64')
    fillOval(ctx, -1.5, -47, 13.5, 12.5, '#f0bd84')
    if (!backView) {
      fillOval(ctx, -5, -45.5, 1.45, 2.6, '#2a3038')
      fillOval(ctx, 5, -45.5, 1.45, 2.6, '#2a3038')
      fillOval(ctx, 0, -40, 2.5, 1.4, '#d48f6e')
      fillOval(ctx, -9, -40.5, 3, 2, 'rgba(226,127,112,.28)')
      fillOval(ctx, 9, -40.5, 3, 2, 'rgba(226,127,112,.28)')
    } else {
      fillOval(ctx, 0, -46, 12, 8, '#62442e')
    }
    fillOval(ctx, 0, -56.5, 22, 6.7, '#a4793c')
    fillOval(ctx, 0, -59, 17, 5.3, '#e6bd65')
    fillOval(ctx, 0, -61.5, 13, 3.4, '#f6da87')
    line(ctx, -13, -56, 13, -56, 1.5, '#9d642f')
    ctx.restore()
  }
}

export default Farmer
